const assert=require("node:assert/strict"),fs=require("node:fs"),vm=require("node:vm");
const sandbox={window:{}};
vm.runInNewContext(fs.readFileSync("assets/report-engine.js","utf8"),sandbox,{filename:"report-engine.js"});
vm.runInNewContext(fs.readFileSync("assets/guidance-engine.js","utf8"),sandbox,{filename:"guidance-engine.js"});
const G=sandbox.window.GroeikompasGuidance,R=sandbox.window.GroeikompasReport;
const base={business:"Fictieve bouwgroep",problem:"Marketingrapportages kosten 8 uur per maand, cijfers uit Google Ads en HubSpot.",goal:"Halveer rapportagetijd zonder fouten.",resources:"HubSpot, GA4 en Google Ads; 2 marketeers",experience:"Geen AI-gebruik",tasks:[],riskStatus:{},riskEvidence:{}};
const input=G.stage(base,0,R.analyse(base));
assert.equal(input.recommendations[0].action.kind,"add-task");
assert.match(input.recommendations[0].value,/rapportages/i);
assert.ok(input.reasoning.some(x=>x.includes("8 uur")));
const proposedTask=input.recommendations[0].value;
const withTask={...base,tasks:[proposedTask],candidateTask:proposedTask,nonAiAlternative:"Dashboardkoppeling",aiNecessity:"onderzoek",aiNecessityReason:"Beide vergelijken"};
const phase3=G.stage(withTask,1,R.analyse(withTask));
assert.match(phase3.summary,/rapportages/i);
assert.match(phase3.recommendations[0].value,/dashboard|CRM/i);
const phase4=G.stage(withTask,3,R.analyse(withTask));
assert.match(phase4.headline,/AI-oplossingen/i);
assert.ok(phase4.recommendations.some(x=>x.action?.kind==="candidate-tool"));
assert.ok(phase4.recommendations.some(x=>/HubSpot/i.test(x.value)));
assert.ok(phase4.recommendations.every(x=>!x.action||x.action.kind!=="approve-tool"));
assert.match(phase4.limitations,/niet geverifieerd/i);
const noai=G.stage({...withTask,aiNecessity:"zonder_ai"},3,R.analyse({...withTask,aiNecessity:"zonder_ai"}));
assert.equal(noai.recommendations[0].value,"Dashboardkoppeling");
assert.ok(noai.recommendations.every(x=>!x.action));
const noAnswers=G.stage({},0,R.analyse({}));
assert.equal(noAnswers.recommendations.length,0);
const content=G.infer({problem:"Social content schrijven voor LinkedIn",goal:"Betere kwaliteit"});
assert.equal(content.kind,"content");
const crm=G.infer({problem:"Leads opvolgen en CRM-data bijwerken"});
assert.equal(crm.kind,"crm");
const attack=G.stage({problem:'<img src=x onerror=alert(1)>',goal:"test"},0,R.analyse({}));
assert.ok(attack.reasoning.some(x=>x.includes("<img")));
assert.match(G.escape(attack.reasoning[0]),/&lt;img/);
console.log("PASS: generated step recommendations, relevance, alternatives, safe proposals and escaped inputs");
