const fs=require("node:fs"),vm=require("node:vm"),assert=require("node:assert/strict");
const context={window:{}};for(const path of ["v3/model.js","v3/advisor.js","v3/report.js"])vm.runInNewContext(fs.readFileSync(path,"utf8"),context);
const M=context.window.GK3,A=context.window.GK3Advisor,R=context.window.GK3Report;
const report=M.newCase("Rapportages BV");report.company.problem="Marketingrapportages kosten tijd";report.company.systems="HubSpot en GA4";
const content=M.newCase("Content BV");content.company.problem="Social content en blogs schrijven kost te veel tijd";
const leads=M.newCase("Leads BV");leads.company.problem="CRM leads worden niet snel opgevolgd";
assert.notEqual(A.classify(report).id,A.classify(content).id);
assert.notEqual(A.classify(content).id,A.classify(leads).id);
const p1=A.plan(report,0),p4=A.plan(report,3);
assert.match(p1.results[0].body,/rapport/i);
assert.ok(p4.results.some(x=>/HubSpot|bestaande software/i.test(x.body)));
assert.ok(p4.results.every(x=>!x.action||x.action!=="approve-tool"));
assert.ok(p4.basis.some(x=>/HubSpot/.test(x)));
assert.equal(p4.results.some(x=>/euro|€[0-9]+/i.test(x.body)),false);
const unsafe=M.newCase("<img src=x onerror=alert(1)>");
unsafe.company.problem="<script>alert(1)</script>";
const html=R.build(unsafe).html,standalone=R.standalone(unsafe);
assert.match(html,/&lt;img/);
assert.doesNotMatch(html,/<img src=x onerror/);
assert.doesNotMatch(html,/<script>alert\(1\)<\/script>/);
assert.match(standalone,/<html/);
assert.match(standalone,/<style>/);
assert.match(html,/FASE 1/);
assert.match(html,/FASE 5/);
assert.match(html,/Geen betrouwbare financiële ROI|Geen aantoonbare ROI/);
console.log("PASS: 3 distinct business personas, grounded tool hypotheses, five-phase report, print export, safe HTML");
